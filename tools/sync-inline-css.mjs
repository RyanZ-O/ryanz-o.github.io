import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const htmlPath = resolve(root, 'index.html');
const cssPath = resolve(root, 'main.css');
const startMarker = '<!-- BEGIN inlined main.css (generated by tools/sync-inline-css.mjs) -->';
const endMarker = '<!-- END inlined main.css -->';
const escapeRegExp = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

const css = readFileSync(cssPath, 'utf8')
  .split(/\r?\n/)
  .map((line) => line.trimEnd())
  .join('\n')
  .trimEnd();
const html = readFileSync(htmlPath, 'utf8');
const block = `${startMarker}\n  <style id="site-styles">\n${css}\n  </style>\n  ${endMarker}`;
const existingBlock = new RegExp(`${escapeRegExp(startMarker)}[\\s\\S]*?${escapeRegExp(endMarker)}`);

let updated;
if (existingBlock.test(html)) {
  updated = html.replace(existingBlock, block);
} else {
  const stylesheet = '  <link rel="stylesheet" href="main.css">';
  if (!html.includes(stylesheet)) {
    throw new Error('Could not find the main.css link or an existing inline CSS block.');
  }
  updated = html.replace(stylesheet, `  ${block}`);
}

if (updated !== html) {
  writeFileSync(htmlPath, updated, 'utf8');
  console.log('Synchronized main.css into index.html.');
} else {
  console.log('Inline CSS is already synchronized.');
}
